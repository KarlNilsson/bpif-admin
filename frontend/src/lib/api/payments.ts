import type {
	MarkFeesPaidResult,
	PaymentRequest,
	PaymentRequestCreate,
	PaymentRequestList
} from '#lib/types/payments.ts';
import { API_BASE, api, type Fetch } from './client.ts';

export function createPaymentRequest(
	fetchFn: Fetch,
	data: PaymentRequestCreate
): Promise<PaymentRequest> {
	return api.post<PaymentRequest>(fetchFn, '/payments', data);
}

export function getPaymentRequest(fetchFn: Fetch, id: string): Promise<PaymentRequest> {
	return api.get<PaymentRequest>(fetchFn, `/payments/${id}`);
}

/**
 * The URL of the QR code. Not a fetch: the browser loads the PNG as an `<img>`
 * source. The image is only ever generated by the API.
 */
export function qrImageUrl(id: string): string {
	return `${API_BASE}/payments/${id}/qr.png`;
}

export function listPaymentRequests(
	fetchFn: Fetch,
	filters: { year?: number; search?: string; linked?: boolean } = {}
): Promise<PaymentRequestList> {
	return api.get<PaymentRequestList>(fetchFn, '/payments', filters);
}

export function markPaymentFeesPaid(
	fetchFn: Fetch,
	id: string,
	memberIds: number[]
): Promise<MarkFeesPaidResult> {
	return api.post<MarkFeesPaidResult>(fetchFn, `/payments/${id}/mark-fees-paid`, {
		member_ids: memberIds
	});
}
